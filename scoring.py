"""
Turning two numbers into one, and one number into something a person can read.
← YOU BUILD THIS IN MILESTONES 4 AND 5

Two functions live here, and both are stubs.

`combine_signals` is where your false-positive decision from Milestone 1
actually gets made. Everything above it — the labels, the appeal path — is
downstream of a number this function produced.

`score_to_label` is where you stop writing for a machine and start writing for
a person. A score of 0.62 means nothing to a writer.

⚠️ Your README's **Signals and Scoring** section has to name the file and
function holding your combining rule. The grader checks your code against what
you claim, so that line should read `scoring.py::combine_signals`.
"""

import config


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine two 0–1 signals into one 0–1 score.

    The rule: a weighted average, `config.WEIGHT_MODEL_SIGNAL * model_score +
    config.WEIGHT_STYLE_SIGNAL * style_score`, weighted heavily toward
    `model_score` (0.9 / 0.1).

    Why that weighting, decided from the four Milestone 4 calibration runs
    (see README for the numbers): `model_score` produced a clean, monotonic
    ordering across all four — clearly-human lowest, clearly-AI highest, the
    two harder cases in between in the direction you'd expect. `style_score`
    did not: on the same four texts it clustered tightly (0.45–0.50) and even
    ran backward once (the formal human paragraph scored more human-like on
    style than the clearly-AI paragraph did). An equal-weight average would
    let a demonstrably weaker, noisier signal drag down a signal that's
    actually discriminating — so `style_score` is kept as a small nudge
    rather than an equal partner, not dropped outright, because it's still
    real information when `model_score` is itself uncertain.

    The split case this rule has to handle: on "clearly human" casual text,
    `model_score` = 0.1766 (confidently human) while `style_score` = 0.5001
    (no opinion — sentences too few to show spread, and plain language reads
    as neither narrow nor varied enough to register). At 0.9/0.1 weighting
    the combined score stays close to `model_score`'s read (≈0.21, still
    clearly human) instead of being dragged toward "unsure" by a signal that
    had nothing to say either way. A 50/50 average would have landed at
    ~0.34 — hugging the human threshold for no good reason.

    Which way this is wrong on purpose: weighting this heavily toward one
    signal means a submission that fools `model_score` specifically (writes
    in a way that reads as unpredictable to GPT-2 while still being AI-
    generated by something else) gets very little pushback from
    `style_score`. That's the trade made here — favoring fewer false
    accusations of real writers over catching every evasion, per
    `criteria.md` #1.
    """
    return (
        config.WEIGHT_MODEL_SIGNAL * model_score
        + config.WEIGHT_STYLE_SIGNAL * style_score
    )


HUMAN_LABEL_TEXT = "We think this was written by a person. No action is needed."

UNSURE_LABEL_TEXT = (
    "We couldn't confidently tell whether this was written by a person or by "
    "AI. This isn't an accusation — it just means our system didn't find a "
    "clear signal either way. Nothing happens to your account because of this."
)

AI_LABEL_TEXT = (
    "We think this was likely written by AI. If you wrote this yourself and "
    "believe this is wrong, you can appeal this decision and a person will "
    "take a look."
)


def score_to_label(score: float) -> tuple[str, str]:
    """
    Turn a score into a guess and the text a reader actually sees.

    Returns:
        (guess, label_text) — where `guess` is a short machine-readable string
        like "ai" / "human" / "unsure", and `label_text` is the full sentence
        shown to a person.

    All three labels are reachable with the current weights/thresholds —
    confirmed with the four Milestone 4 calibration texts: the clearly-human
    text (combined 0.209) lands `human`, the formal-human and lightly-edited-AI
    texts (0.470, 0.638) both land `unsure`, and the clearly-AI text (0.678)
    lands `ai`. See README's Label Variants section.
    """
    if score >= config.AI_THRESHOLD:
        return "ai", AI_LABEL_TEXT
    if score <= config.HUMAN_THRESHOLD:
        return "human", HUMAN_LABEL_TEXT
    return "unsure", UNSURE_LABEL_TEXT


def score_to_confidence(score: float) -> float:
    """
    How sure the system is of its own guess, as a 0–1 number for the response.
    Not asked for by name in the brief, but `confidence` is in the required
    response shape, so it needs a real rule rather than staying `null`.

    In the human/AI bands: 0 at the threshold edge (barely past the line) up
    to 1 at the far end (score 0.0 for human, 1.0 for AI). In the unsure band:
    always 0 — "unsure" already says the system isn't confident, so a nonzero
    number there would contradict the label text sitting right next to it.
    """
    if score <= config.HUMAN_THRESHOLD:
        return round((config.HUMAN_THRESHOLD - score) / config.HUMAN_THRESHOLD, 4)
    if score >= config.AI_THRESHOLD:
        span = 1.0 - config.AI_THRESHOLD
        return round((score - config.AI_THRESHOLD) / span, 4)
    return 0.0


def label_ranges() -> list[tuple[str, str]]:
    """
    The score range each label covers. Your README needs these beside the
    label text — given to you so the numbers can't drift apart from config.py.
    """
    return [
        ("high-confidence human", f"0.00 – {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} – {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} – 1.00"),
    ]
